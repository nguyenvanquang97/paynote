#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const {spawn} = require('child_process');

const projectRoot = path.resolve(__dirname, '..');
const workspaceRoot = path.resolve(projectRoot, '..', '..');
const envPath = fs.existsSync(path.join(projectRoot, '.env'))
  ? path.join(projectRoot, '.env')
  : path.join(workspaceRoot, '.env');
const generatedEnvPath = path.join(projectRoot, 'src', 'config', 'runtimeEnv.local.ts');

const parseEnvFile = (content) => {
  const env = {};
  content.split(/\r?\n/).forEach((line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      return;
    }
    const idx = trimmed.indexOf('=');
    if (idx <= 0) {
      return;
    }
    const key = trimmed.slice(0, idx).trim();
    let value = trimmed.slice(idx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  });
  return env;
};

const loadDotEnv = () => {
  if (!fs.existsSync(envPath)) {
    return {};
  }
  try {
    const raw = fs.readFileSync(envPath, 'utf8');
    return parseEnvFile(raw);
  } catch (error) {
    console.warn('[with-env] Failed to read .env:', error);
    return {};
  }
};

const writeGeneratedEnvModule = (env) => {
  const safe = {
    GEMINI_API_KEY: typeof env.GEMINI_API_KEY === 'string' ? env.GEMINI_API_KEY : '',
    GOOGLE_API_KEY: typeof env.GOOGLE_API_KEY === 'string' ? env.GOOGLE_API_KEY : '',
    OPENAI_API_KEY: typeof env.OPENAI_API_KEY === 'string' ? env.OPENAI_API_KEY : '',
    PAYNOTE_AI_PROVIDER: typeof env.PAYNOTE_AI_PROVIDER === 'string' ? env.PAYNOTE_AI_PROVIDER : '',
    PAYNOTE_AI_API_KEY: typeof env.PAYNOTE_AI_API_KEY === 'string' ? env.PAYNOTE_AI_API_KEY : '',
    PAYNOTE_AI_PROXY_URL: typeof env.PAYNOTE_AI_PROXY_URL === 'string' ? env.PAYNOTE_AI_PROXY_URL : '',
    PAYNOTE_AI_PROXY_TOKEN: typeof env.PAYNOTE_AI_PROXY_TOKEN === 'string' ? env.PAYNOTE_AI_PROXY_TOKEN : '',
    PAYNOTE_AI_MODEL: typeof env.PAYNOTE_AI_MODEL === 'string' ? env.PAYNOTE_AI_MODEL : '',
    PAYNOTE_AI_LOCAL_ONLY: typeof env.PAYNOTE_AI_LOCAL_ONLY === 'string' ? env.PAYNOTE_AI_LOCAL_ONLY : '',
    PAYNOTE_AI_TIMEOUT_MS: typeof env.PAYNOTE_AI_TIMEOUT_MS === 'string' ? env.PAYNOTE_AI_TIMEOUT_MS : '',
    PAYNOTE_API_URL: typeof env.PAYNOTE_API_URL === 'string' ? env.PAYNOTE_API_URL : '',
    PAYNOTE_AUTH_REDIRECT_URL: typeof env.PAYNOTE_AUTH_REDIRECT_URL === 'string' ? env.PAYNOTE_AUTH_REDIRECT_URL : '',
    SUPABASE_URL: typeof env.SUPABASE_URL === 'string' ? env.SUPABASE_URL : '',
    SUPABASE_ANON_KEY: typeof env.SUPABASE_ANON_KEY === 'string' ? env.SUPABASE_ANON_KEY : '',
  };
  const content = [
    '// Auto-generated by scripts/with-env.js. Do not edit manually.',
    'export const RUNTIME_ENV = {',
    `  GEMINI_API_KEY: ${JSON.stringify(safe.GEMINI_API_KEY)},`,
    `  GOOGLE_API_KEY: ${JSON.stringify(safe.GOOGLE_API_KEY)},`,
    `  OPENAI_API_KEY: ${JSON.stringify(safe.OPENAI_API_KEY)},`,
    `  PAYNOTE_AI_PROVIDER: ${JSON.stringify(safe.PAYNOTE_AI_PROVIDER)},`,
    `  PAYNOTE_AI_API_KEY: ${JSON.stringify(safe.PAYNOTE_AI_API_KEY)},`,
    `  PAYNOTE_AI_PROXY_URL: ${JSON.stringify(safe.PAYNOTE_AI_PROXY_URL)},`,
    `  PAYNOTE_AI_PROXY_TOKEN: ${JSON.stringify(safe.PAYNOTE_AI_PROXY_TOKEN)},`,
    `  PAYNOTE_AI_MODEL: ${JSON.stringify(safe.PAYNOTE_AI_MODEL)},`,
    `  PAYNOTE_AI_LOCAL_ONLY: ${JSON.stringify(safe.PAYNOTE_AI_LOCAL_ONLY)},`,
    `  PAYNOTE_AI_TIMEOUT_MS: ${JSON.stringify(safe.PAYNOTE_AI_TIMEOUT_MS)},`,
    `  PAYNOTE_API_URL: ${JSON.stringify(safe.PAYNOTE_API_URL)},`,
    `  PAYNOTE_AUTH_REDIRECT_URL: ${JSON.stringify(safe.PAYNOTE_AUTH_REDIRECT_URL)},`,
    `  SUPABASE_URL: ${JSON.stringify(safe.SUPABASE_URL)},`,
    `  SUPABASE_ANON_KEY: ${JSON.stringify(safe.SUPABASE_ANON_KEY)},`,
    '} as const;',
    '',
  ].join('\n');
  fs.writeFileSync(generatedEnvPath, content, 'utf8');
};

const fileEnv = loadDotEnv();
const mergedEnv = {...process.env, ...fileEnv};
writeGeneratedEnvModule(mergedEnv);

const args = process.argv.slice(2);
if (args.length === 1 && args[0] === '--generate-only') {
  process.exit(0);
}

if (args.length === 0) {
  console.error('[with-env] Missing command. Example: node scripts/with-env.js react-native start');
  process.exit(1);
}

const child = spawn(args[0], args.slice(1), {
  stdio: 'inherit',
  shell: true,
  env: mergedEnv,
});

child.on('exit', (code, signal) => {
  if (signal) {
    process.kill(process.pid, signal);
    return;
  }
  process.exit(code ?? 1);
});
