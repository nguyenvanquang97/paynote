const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const planPath = path.join(root, 'paynote_notification_refactor_plan.md');
const outPath = path.join(root, 'src/services/notifications/notificationPlanTemplates.ts');
const kotlinOutPath = path.join(root, 'android/app/src/main/java/com/paynote/app/PeriodicPlanFallbackTemplates.kt');

const md = fs.readFileSync(planPath, 'utf8');
const start = md.indexOf('# 14. Bộ message seed chi tiết');
const end = md.indexOf('## 15. Native fallback Kotlin');

if (start < 0 || end < 0 || end <= start) {
  throw new Error('Could not find notification message seed section in plan');
}

const SEVERITY_BY_TRIGGER = {
  budget_50: 'low',
  budget_80: 'medium',
  budget_100: 'high',
  budget_120: 'critical',
  large_transaction: 'high',
  repeat_category_today: 'medium',
  repeat_category_week: 'medium',
  late_night_spending: 'high',
  bank_transaction_detected: 'medium',
  salary_received: 'low',
  income_received: 'low',
  no_spend_day: 'low',
  saving_streak: 'medium',
  duplicate_transaction: 'low',
  missed_transaction: 'high',
  end_of_day_summary: 'medium',
  end_of_month_warning: 'high',
};

const CONTEXT_TRIGGER = {
  food: 'repeat_category_today',
  cafe: 'repeat_category_today',
  shopping: 'large_transaction',
  transport: 'repeat_category_today',
  bill: 'bank_transaction_detected',
  rent: 'budget_100',
};

const PERSONAS = new Set(['advisor', 'wallet_pet', 'toxic_friend', 'vietnamese_parent']);
const CONTEXTS = new Set(['food', 'cafe', 'shopping', 'transport', 'bill', 'rent']);

const slug = value => value
  .toLowerCase()
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .replace(/[^a-z0-9]+/g, '_')
  .replace(/^_+|_+$/g, '');

const tierForIndex = index => {
  if (index === 0) return 1;
  if (index === 1 || index === 2) return 2;
  if (index === 3) return 3;
  return 4;
};

const sectionToScope = raw => {
  const section = raw.trim().toLowerCase();
  if (section.includes(' / ')) {
    return {triggers: section.split('/').map(x => x.trim()), context: 'any'};
  }
  if (SEVERITY_BY_TRIGGER[section]) {
    return {triggers: [section], context: 'any'};
  }
  const context = section.replace(/\s+context$/, '').trim();
  if (CONTEXTS.has(context)) {
    return {triggers: [CONTEXT_TRIGGER[context]], context};
  }
  return null;
};

const body = md.slice(start, end);
const lines = body.split(/\r?\n/);
let currentSection = null;
let currentPersona = null;
let currentBlock = [];
const templates = [];
const seen = new Set();

const flush = () => {
  if (!currentSection || !currentPersona || currentBlock.length === 0) {
    currentBlock = [];
    return;
  }
  const scope = sectionToScope(currentSection);
  if (!scope || !PERSONAS.has(currentPersona)) {
    currentBlock = [];
    return;
  }
  currentBlock.forEach((message, index) => {
    scope.triggers.forEach(trigger => {
      if (!SEVERITY_BY_TRIGGER[trigger]) return;
      const key = `${trigger}:${currentPersona}:${scope.context}:${message}`;
      if (seen.has(key)) return;
      seen.add(key);
      templates.push({
        id: `plan_${trigger}_${currentPersona}_${scope.context}_${slug(message).slice(0, 36)}_${index + 1}`,
        trigger,
        persona: currentPersona,
        severity: SEVERITY_BY_TRIGGER[trigger],
        tier: tierForIndex(index),
        context: scope.context,
        body: message,
        tags: ['plan', `tier_${tierForIndex(index)}`],
        origin: 'plan',
        planRef: `14:${currentSection}:${currentPersona}:${index + 1}`,
      });
    });
  });
  currentBlock = [];
};

for (const line of lines) {
  const sectionMatch = line.match(/^##\s+14\.\d+\.\s+(.+?)\s*$/);
  if (sectionMatch) {
    flush();
    currentSection = sectionMatch[1].trim();
    currentPersona = null;
    continue;
  }

  const personaMatch = line.match(/^###\s+(.+?)\s*$/);
  if (personaMatch) {
    flush();
    const persona = personaMatch[1].trim();
    currentPersona = PERSONAS.has(persona) ? persona : null;
    continue;
  }

  const messageMatch = line.match(/^\s*"((?:[^"\\]|\\.)*)",?\s*$/);
  if (messageMatch && currentSection && currentPersona) {
    currentBlock.push(messageMatch[1].replace(/\\"/g, '"'));
  }
}
flush();

const content = `// Auto-generated from paynote_notification_refactor_plan.md by scripts/generate-notification-plan-templates.js.
// Do not edit this file manually; edit the plan or generator instead.
import type {NotificationTemplate} from './notificationTypes';

export const PLAN_NOTIFICATION_TEMPLATES: NotificationTemplate[] = ${JSON.stringify(templates, null, 2)};
`;

fs.writeFileSync(outPath, content);

const escapeKotlin = value => value
  .replace(/\\/g, '\\\\')
  .replace(/"/g, '\\"')
  .replace(/\$/g, '\\$');

const placeholderDefaults = {
  '{categoryLabel}': 'chi tiêu',
  '{percent}': '80',
  '{spentText}': 'khoản đã chi',
  '{limitText}': 'ngân sách',
  '{amountText}': 'khoản này',
  '{count}': 'vài',
  '{days}': 'vài',
  '{daysLeft}': 'vài',
};

const nativeTriggerPriority = new Set([
  'late_night_spending',
  'end_of_day_summary',
  'end_of_month_warning',
  'no_spend_day',
  'saving_streak',
  'repeat_category_today',
  'budget_80',
  'budget_100',
  'budget_120',
]);

const nativePools = {
  advisor: [],
  wallet_pet: [],
  toxic_friend: [],
  vietnamese_parent: [],
};

const normalizeNativeBody = bodyValue => Object.entries(placeholderDefaults)
  .reduce((text, [key, replacement]) => text.replaceAll(key, replacement), bodyValue);

for (const template of templates) {
  if (!nativeTriggerPriority.has(template.trigger)) continue;
  const pool = nativePools[template.persona];
  if (!pool) continue;
  const normalizedBody = normalizeNativeBody(template.body);
  if (normalizedBody.includes('{') || normalizedBody.includes('}')) continue;
  if (pool.some(item => item.body === normalizedBody)) continue;
  pool.push({
    body: normalizedBody,
    tier: template.tier || 1,
  });
}

const kotlinList = (items) => {
  const ordered = items
    .sort((a, b) => (a.tier - b.tier) || a.body.localeCompare(b.body))
    .slice(0, 60);
  return ordered
    .map(item => `        NativePlanTemplate("${escapeKotlin(item.body)}", ${item.tier})`)
    .join(',\n');
};

const kotlinContent = `package com.paynote.app

import kotlin.random.Random

data class NativePlanTemplate(
    val body: String,
    val tier: Int
)

object PeriodicPlanFallbackTemplates {
    private val advisor = listOf(
${kotlinList(nativePools.advisor)}
    )

    private val walletPet = listOf(
${kotlinList(nativePools.wallet_pet)}
    )

    private val toxicFriend = listOf(
${kotlinList(nativePools.toxic_friend)}
    )

    private val vietnameseParentSoft = listOf(
${kotlinList(nativePools.vietnamese_parent.filter(item => !/\\bmày\\b|\\btao\\b/i.test(item.body)))}
    )

    private val vietnameseParentStrong = listOf(
${kotlinList(nativePools.vietnamese_parent)}
    )

    fun pick(toneMode: String, allowStrongLanguage: Boolean, tier: Int): String {
        val pool = when (toneMode) {
            "gentle", "advisor" -> advisor
            "cute", "wallet_pet" -> walletPet
            "angry", "strict", "vietnamese_parent" -> if (allowStrongLanguage) vietnameseParentStrong else vietnameseParentSoft
            else -> toxicFriend
        }
        if (pool.isEmpty()) {
            return PeriodicFallbackTemplates.pick(toneMode, allowStrongLanguage, tier)
        }
        val tierPool = pool.filter { kotlin.math.abs(it.tier - tier) <= 1 }.ifEmpty { pool }
        return tierPool[Random.nextInt(tierPool.size)].body
    }
}
`;

fs.writeFileSync(kotlinOutPath, kotlinContent);
console.log(`Generated ${templates.length} plan notification templates`);
console.log(`Generated native plan fallback pools: advisor=${nativePools.advisor.length}, wallet_pet=${nativePools.wallet_pet.length}, toxic_friend=${nativePools.toxic_friend.length}, vietnamese_parent=${nativePools.vietnamese_parent.length}`);
